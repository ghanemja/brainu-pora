// Horizontal bar with an optional threshold tick — used for rubric
// pass bars and awardee per-section scores.
function ThresholdBar({ value, threshold, color, height = 8 }) {
  return (
    <div style={{
      position: "relative", height, borderRadius: height / 2,
      background: "var(--c-bg-elev-2)",
      border: "1px solid var(--c-line)",
      overflow: "hidden",
    }}>
      <div style={{
        position: "absolute", left: 0, top: 0, bottom: 0,
        width: `${Math.max(0, Math.min(1, value || 0)) * 100}%`,
        background: color,
        borderRadius: height / 2,
      }} />
      {threshold != null && (
        <div style={{
          position: "absolute", top: -1, bottom: -1,
          left: `${Math.max(0, Math.min(1, threshold)) * 100}%`,
          width: 2, background: "var(--c-ink)", opacity: 0.75,
        }} />
      )}
    </div>
  );
}

function ItemTypeTag({ type }) {
  const c = ITEM_TYPE_COLOR[type] || "var(--c-ink-muted)";
  return (
    <span className="tag" style={{
      color: c, borderColor: `color-mix(in oklch, ${c} 50%, transparent)`,
    }}>{type}</span>
  );
}

