function ATPCerts({ onViewAgent }) {
  if (!window.ATP_DATA) return <AtpDataMissing />;
  const D = window.ATP_DATA;
  const certs = D.CERTS || [];

  // Consume the cross-screen badge-click handoff (set by any screen that
  // renders a CertBadge and calls goto('certs')) plus the hash-router
  // deep-link handoffs: window.ATP_CERT_FOCUS (#/cert/{id}) and
  // window.ATP_EVIDENCE_FOCUS (#/evidence/{id}) — docs/HARDENING.md P3.
  const arrivedViaBadge = useRef(false);

  // Evidence focus is consumed first: it also decides which cert to open.
  const [evFocus, setEvFocus] = useState(() => {
    const f = window.ATP_EVIDENCE_FOCUS || null;
    if (f) window.ATP_EVIDENCE_FOCUS = null;
    return f;
  });

  const certOfEvidence = (evId) => {
    if (!evId || typeof D.evidenceById !== "function") return null;
    const ev = D.evidenceById(evId);
    return (ev && ev.certId && certs.some(c => c.id === ev.certId)) ? ev.certId : null;
  };

  const [selId, setSelId] = useState(() => {
    const evCert = certOfEvidence(evFocus);
    if (evCert) return evCert; // the focused row does its own scroll
    const f = window.ATP_CERT_FOCUS;
    if (f && certs.some(c => c.id === f)) {
      window.ATP_CERT_FOCUS = null;
      arrivedViaBadge.current = true;
      return f;
    }
    const flagship = certs.find(c => c.id === "atp-l4-math");
    return (flagship || certs[0] || {}).id || null;
  });
  const detailRef = useRef(null);

  useEffect(() => {
    if (arrivedViaBadge.current && detailRef.current) {
      // Landed here from a badge click elsewhere — go straight to the meaning.
      detailRef.current.scrollIntoView({ behavior: "smooth", block: "start" });
    }
  }, []);

  // Deep link fired while this screen is already mounted (the shell's hash
  // router sets the window globals first — its listener registered at App
  // mount, before ours, so ordering holds). Re-consume them here.
  useEffect(() => {
    const consume = () => {
      const e = window.ATP_EVIDENCE_FOCUS || null;
      if (e) {
        window.ATP_EVIDENCE_FOCUS = null;
        const evCert = certOfEvidence(e);
        if (evCert) setSelId(evCert);
        setEvFocus(e);
        return;
      }
      const c = window.ATP_CERT_FOCUS || null;
      if (c && certs.some(x => x.id === c)) {
        window.ATP_CERT_FOCUS = null;
        setSelId(c);
        setTimeout(() => {
          if (detailRef.current) {
            detailRef.current.scrollIntoView({ behavior: "smooth", block: "start" });
          }
        }, 60);
      }
    };
    window.addEventListener("hashchange", consume);
    return () => window.removeEventListener("hashchange", consume);
  }, []);

  const pick = id => {
    setSelId(id);
    setTimeout(() => {
      if (detailRef.current) {
        detailRef.current.scrollIntoView({ behavior: "smooth", block: "start" });
      }
    }, 60);
  };

  const sel = certs.find(c => c.id === selId) || null;
  const exampleCert = certs.find(c => c.id === "atp-l4-math") || certs[0] || null;
  const layerMeta = n =>
    (D.LAYERS || []).find(l => l.n === n) ||
    { title: ((D.STANDARD.levels || {})["L" + n] || {}).title || "", color: GOLD };

  return (
    <div style={{ minHeight: "calc(100vh - 56px)", padding: "44px 28px 80px" }}>
      <div style={{ maxWidth: 1120, margin: "0 auto" }}>

        {/* Masthead */}
        <div style={{ marginBottom: 22 }}>
          <div className="t-tag" style={{ color: GOLD }}>◈ CERTIFICATIONS</div>
          <h1 className="t-display" style={{ margin: "6px 0 4px" }}>
            The registry of meaning.
          </h1>
          <p className="t-cap" style={{ fontSize: 13.5, maxWidth: 680 }}>
            Every ATP badge resolves to this page: the exam it names, the rubric it was
            graded on, the conditions it was passed under, and the evidence trail of every
            agent that holds it.
          </p>
        </div>

        {/* The standard */}
        <StandardCard standard={D.STANDARD} exampleCert={exampleCert} />

        {/* Catalog grouped by layer */}
        <SectionTitle kicker="CATALOG" title="Certifications by layer" />
        <div style={{ marginTop: 12 }}>
          {[1, 2, 3, 4, 5, 6, 7].map(n => {
            const list = certs.filter(c => c.layer === n);
            if (!list.length) return null;
            const meta = layerMeta(n);
            return (
              <div key={n} style={{ marginBottom: 18 }}>
                <div style={{
                  display: "flex", alignItems: "center", gap: 10, marginBottom: 8,
                }}>
                  <LevelGlyph n={n} size={22} />
                  <span className="t-tag" style={{ color: meta.color || GOLD }}>
                    L{n} · {meta.title}
                  </span>
                  <div className="hr" style={{ flex: 1 }} />
                  <span className="t-mono" style={{ fontSize: 10.5, color: "var(--c-ink-dim)" }}>
                    {list.length} cert{list.length === 1 ? "" : "s"}
                  </span>
                </div>
                <div style={{
                  display: "grid",
                  gridTemplateColumns: "repeat(auto-fill, minmax(220px, 1fr))",
                  gap: 10,
                }}>
                  {list.map(c => (
                    <CertCatalogCard key={c.id} cert={c}
                      active={c.id === selId} onPick={() => pick(c.id)} />
                  ))}
                </div>
              </div>
            );
          })}
        </div>

        {/* Full detail — meaning + evidence */}
        {sel && (
          <CertDetail key={sel.id} cert={sel}
            onViewAgent={onViewAgent} detailRef={detailRef}
            evidenceFocusId={evFocus}
            onEvidenceFocusDone={() => setEvFocus(null)} />
        )}
      </div>
    </div>
  );
}

