// ── Catalog card for one cert ──
function CertCatalogCard({ cert, active, onPick }) {
  const [hover, setHover] = useState(false);
  const accent = cert.color || GOLD;
  return (
    <div
      onClick={onPick}
      onMouseEnter={() => setHover(true)}
      onMouseLeave={() => setHover(false)}
      className="card"
      style={{
        cursor: "pointer", padding: 14, textAlign: "center",
        borderColor: active
          ? `color-mix(in oklch, ${accent} 60%, transparent)`
          : hover ? "var(--c-line-strong)" : "var(--c-line)",
        background: active
          ? `color-mix(in oklch, ${accent} 6%, var(--c-bg-elev))`
          : "var(--c-bg-elev)",
        boxShadow: active
          ? `0 0 0 3px color-mix(in oklch, ${accent} 16%, transparent)`
          : "none",
        transform: hover && !active ? "translateY(-2px)" : "none",
        transition: "transform 140ms, border-color 140ms, box-shadow 140ms",
      }}
    >
      <CertBadge cert={cert} onClick={onPick} />
      <div className="t-cap" style={{ marginTop: 8, fontSize: 11.5 }}>
        {cert.domain} · {(cert.awards || []).length} awarded
      </div>
      <div className="t-cap" style={{
        marginTop: 4, fontSize: 10.5,
        color: active ? accent : "var(--c-ink-dim)",
      }}>
        {active ? "▼ shown below" : "meaning + evidence →"}
      </div>
    </div>
  );
}

