// ── Screen ───────────────────────────────────────────────────────
function ATPGovernance() {
  const data = window.ATP_DATA;
  if (!data) return <AtpDataMissing />;

  const tiers = data.TIERS || {};
  const policies = data.POLICIES || [];
  const agents = data.AGENTS || [];
  const rl = data.RL || {};
  const weights = rl.rewardWeights || { L1: 0.04, L2: 0.06, L3: 0.08, L4: 0.12, L5: 0.20, L6: 0.24, L7: 0.26 };

  // Seed log is stored oldest → newest; the exhibit reads newest first.
  const [log, setLog] = useState(() => [...(rl.hitlLog || [])].reverse());

  useEffect(() => {
    let dead = false;
    (async () => {
      try {
        if (window.BU_API && BU_API.atpHitlLog) {
          const r = await BU_API.atpHitlLog(100);
          if (!dead && r && Array.isArray(r.events) && r.events.length) setLog(r.events);
        }
      } catch (e) { /* keep seed fallback */ }
    })();
    return () => { dead = true; };
  }, []);

  const heavyRatio = useMemo(() => {
    const lo = Number(weights.L1) || 0.04, hi = Number(weights.L7) || 0.26;
    return lo > 0 ? (hi / lo) : 0;
  }, [weights]);

  // Submit via BU_API.atpHitl; on offline, append locally as unsynced (demo).
  const submitReward = async payload => {
    let res = null;
    try {
      res = window.BU_API && BU_API.atpHitl
        ? await BU_API.atpHitl(payload)
        : { ok: false, offline: true };
    } catch (e) {
      res = e && e.forbidden
        ? { ok: false, forbidden: true }
        : { ok: false, offline: true };
    }
    // Role too low (403): tell the rater — do NOT fake an unsynced demo row.
    if (res && res.forbidden) return { forbidden: true };
    if (!res || res.offline || res.ok === false) {
      const w = Number(weights["L" + payload.layer]) || 0;
      const evt = {
        ts: new Date().toISOString().slice(0, 16).replace("T", " "),
        rater: payload.rater,
        agentId: payload.agentId,
        layer: payload.layer,
        signal: payload.signal,
        weightedDelta: Math.round(payload.signal * 0.2 * (w / 0.26) * 1000) / 1000,
        reason: payload.reason,
        auditId: "local-" + Date.now().toString(36),
        unsynced: true,
      };
      setLog(prev => [evt, ...prev]);
      return { offline: true };
    }
    const evt = res.event || res; // POST returns the enriched appended event
    setLog(prev => [evt, ...prev]);
    return { offline: false };
  };

  return (
    <div style={{ minHeight: "calc(100vh - 56px)", padding: "48px 28px 80px" }}>
      <div style={{ maxWidth: 1120, margin: "0 auto" }}>

        {/* Header */}
        <div style={{ marginBottom: 36, maxWidth: 760 }}>
          <div className="t-tag" style={{ color: GOLD }}>GOVERNANCE · AUDITABLE BY DESIGN</div>
          <h1 className="t-display" style={{ margin: "6px 0 8px" }}>
            Autonomy is earned, scoped, and logged.
          </h1>
          <p className="t-cap" style={{ fontSize: 14, lineHeight: 1.6, margin: 0 }}>
            Agents self-authorize only inside a sandbox matched to their tier. Policies bind
            them by name. And every human judgment that shapes their reinforcement lands in an
            append-only audit log — rater, weighted delta, reason, audit id. Nothing about the
            reward channel is off the books.
          </p>
        </div>

        {/* Exhibit 1 — tier matrix */}
        <section style={{ marginBottom: 44 }}>
          <SectionTitle kicker="SANDBOXED SELF-AUTHORIZATION" title="Three tiers, three sandboxes" />
          <p className="t-cap" style={{ margin: "0 0 16px", maxWidth: 680, lineHeight: 1.55 }}>
            An agent may only do what its tier's sandbox allows — and the deny list is printed
            as prominently as the allow list. Promotion between tiers is a certification event,
            not a config flip.
          </p>
          <div style={{
            display: "grid",
            gridTemplateColumns: "repeat(auto-fit, minmax(280px, 1fr))",
            gap: 14, alignItems: "stretch",
          }}>
            {TIER_ORDER.filter(k => tiers[k]).map(k => (
              <TierColumn key={k} tierKey={k} tier={tiers[k]}
                          agents={agents.filter(a => a.tier === k)} />
            ))}
          </div>
        </section>

        {/* Exhibit 2 — policy registry */}
        <section style={{ marginBottom: 44 }}>
          <SectionTitle kicker="POLICY REGISTRY" title="What binds the agents" />
          <p className="t-cap" style={{ margin: "0 0 16px", maxWidth: 680, lineHeight: 1.55 }}>
            Company policy, contracts, regulation, and practice — each policy lists its rules
            and the agents bound to them. A binding is visible here before it is enforced anywhere.
          </p>
          <div style={{
            display: "grid",
            gridTemplateColumns: "repeat(auto-fit, minmax(300px, 1fr))",
            gap: 14, alignItems: "stretch",
          }}>
            {policies.map(p => <PolicyCard key={p.id} policy={p} />)}
          </div>
        </section>

        {/* Exhibit 2b — license registry (Phase 4 billing) */}
        <section style={{ marginBottom: 44 }}>
          <SectionTitle kicker="LICENSES" title="Who holds a key, and what it may call" />
          <p className="t-cap" style={{ margin: "0 0 16px", maxWidth: 680, lineHeight: 1.55 }}>
            Licenses are org-scoped commercial bindings: each key gates the delivery
            endpoint, every call is metered, and revocation is enforced on the next
            call — not the next billing cycle. Issuing and revoking require org admin.
          </p>
          <LicensesCard agents={agents} />
        </section>

        {/* Exhibit 3 — reinforcement */}
        <section>
          <SectionTitle kicker="REINFORCEMENT" title="Human-in-the-loop reward, weighted where it matters" />
          <div style={{
            display: "grid", gridTemplateColumns: "1.4fr 1fr", gap: 14,
            marginBottom: 14, alignItems: "stretch",
          }}>
            <div className="card" style={{ padding: 18 }}>
              <div className="t-tag" style={{ color: "var(--c-ink-dim)", marginBottom: 10 }}>
                RL REWARD WEIGHTS BY LAYER · NORMALIZED
              </div>
              <RewardWeightChart weights={weights} />
              <div className="t-cap" style={{ marginTop: 12, lineHeight: 1.55 }}>
                Reinforcement is deliberately concentrated where the company's own knowledge
                lives: a +1 at L7 moves the policy {heavyRatio ? `${heavyRatio.toFixed(1)}×` : "far"} more
                than the same +1 at L1. Foundational skill is table stakes; judgment inside the
                org is what gets rewarded.
              </div>
              <div className="t-mono" style={{ fontSize: 11, color: "var(--c-ink-dim)", marginTop: 8 }}>
                Δ = signal × 0.2 × (weight[layer] / 0.26)
              </div>
            </div>
            <HitlForm agents={agents} weights={weights} onSubmit={submitReward} />
          </div>
          <HitlTable rows={log} />
        </section>
      </div>
    </div>
  );
}

