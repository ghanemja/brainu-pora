// ── Exhibit 3a: reward-weight bar chart (inline SVG) ─────────────
function RewardWeightChart({ weights }) {
  const entries = [1, 2, 3, 4, 5, 6, 7].map(n => ({ n, w: Number(weights["L" + n]) || 0 }));
  const max = Math.max(0.01, ...entries.map(e => e.w));
  const heavyShare = entries.slice(4).reduce((s, e) => s + e.w, 0);

  const W = 560, H = 240;
  const padL = 30, padR = 14, padT = 48, padB = 30;
  const innerW = W - padL - padR, innerH = H - padT - padB;
  const step = innerW / entries.length;
  const barW = Math.min(44, step * 0.6);
  const baseY = H - padB;
  const xOf = i => padL + i * step + (step - barW) / 2;

  const regionX = padL + 4 * step + 3;
  const regionW = 3 * step - 6;

  return (
    <svg viewBox={`0 0 ${W} ${H}`} style={{ width: "100%", height: "auto", display: "block" }}
         role="img" aria-label="RL reward weights by layer — L5 to L7 carry most of the reward mass">
      {/* company-layers emphasis region behind L5–L7 */}
      <rect x={regionX} y={padT - 16} width={regionW} height={innerH + 16}
            rx="6" fill={GOLD} fillOpacity="0.07"
            stroke={GOLD} strokeOpacity="0.35" strokeDasharray="3 4" strokeWidth="1" />
      <text x={regionX + regionW / 2} y={padT - 24} textAnchor="middle"
            fontSize="10" fontFamily="var(--f-mono)" fill={GOLD} letterSpacing="0.08em">
        L5–L7 · {Math.round(heavyShare * 100)}% OF REWARD MASS
      </text>

      {/* bars */}
      {entries.map((e, i) => {
        const h = (e.w / max) * innerH;
        const y = baseY - h;
        return (
          <g key={e.n}>
            <rect x={xOf(i)} y={y} width={barW} height={h} rx="3"
                  fill={layerColor(e.n)} fillOpacity={e.n >= 5 ? 0.92 : 0.55}>
              <title>{`L${e.n} — weight ${e.w}`}</title>
            </rect>
            <text x={xOf(i) + barW / 2} y={y - 6} textAnchor="middle"
                  fontSize="10" fontFamily="var(--f-mono)" fill="var(--c-ink-muted)">
              {e.w.toFixed(2)}
            </text>
            <text x={xOf(i) + barW / 2} y={H - 12} textAnchor="middle"
                  fontSize="10" fontFamily="var(--f-mono)" fill={layerColor(e.n)}>
              L{e.n}
            </text>
          </g>
        );
      })}

      {/* baseline */}
      <line x1={padL} y1={baseY} x2={W - padR} y2={baseY}
            stroke="var(--c-line-strong)" strokeWidth="1" />
    </svg>
  );
}

// ── Exhibit 3b: log-human-reward form ────────────────────────────
function HitlForm({ agents, weights, onSubmit }) {
  const first = agents[0] || null;
  const [agentId, setAgentId] = useState(first ? first.id : "");
  const [layer, setLayer] = useState(first ? first.level : 5);
  const [signal, setSignal] = useState(1);
  const [reason, setReason] = useState("");
  const [rater, setRater] = useState("human-reviewer");
  const [busy, setBusy] = useState(false);
  const [note, setNote] = useState(null); // {offline:bool, forbidden:bool}

  const w = Number(weights["L" + layer]) || 0;
  const preview = signal * 0.2 * (w / 0.26);
  const canSubmit = agentId && reason.trim() && !busy;

  const handleAgent = id => {
    setAgentId(id);
    const a = agents.find(x => x.id === id);
    if (a && a.level) setLayer(a.level);
  };

  const submit = async () => {
    if (!canSubmit) return;
    setBusy(true);
    setNote(null);
    const res = await onSubmit({
      agentId, layer, signal, reason: reason.trim(), rater: rater.trim() || "human-reviewer",
    });
    setBusy(false);
    setNote(res);
    // Keep the typed reason when the submit was refused for role — the
    // rater may re-submit after switching to an SME/admin session.
    if (!(res && res.forbidden)) setReason("");
  };

  return (
    <div className="card" style={{ padding: 18, display: "flex", flexDirection: "column", gap: 12 }}>
      <div>
        <div className="t-tag" style={{ color: GOLD, marginBottom: 4 }}>LOG HUMAN REWARD</div>
        <div className="t-cap" style={{ lineHeight: 1.5 }}>
          One judgment, one record. Your signal is weighted by layer, appended to the
          audit log, and folded into the agent's reinforcement.
        </div>
      </div>

      <label style={{ display: "block" }}>
        <div className="t-tag" style={{ color: "var(--c-ink-dim)", marginBottom: 4 }}>AGENT</div>
        <select value={agentId} onChange={e => handleAgent(e.target.value)} style={inputStyle}>
          {agents.map(a => (
            <option key={a.id} value={a.id}>
              {a.name} — L{a.level} · {a.tier}
            </option>
          ))}
        </select>
      </label>

      <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: 10 }}>
        <label style={{ display: "block" }}>
          <div className="t-tag" style={{ color: "var(--c-ink-dim)", marginBottom: 4 }}>LAYER</div>
          <select value={layer} onChange={e => setLayer(+e.target.value)} style={inputStyle}>
            {[1, 2, 3, 4, 5, 6, 7].map(n => (
              <option key={n} value={n}>
                L{n} · weight {(Number(weights["L" + n]) || 0).toFixed(2)}
              </option>
            ))}
          </select>
        </label>
        <div>
          <div className="t-tag" style={{ color: "var(--c-ink-dim)", marginBottom: 4 }}>SIGNAL</div>
          <div style={{ display: "flex", gap: 6 }}>
            {[{ v: 1, label: "+1 reinforce", c: "var(--c-cs)" },
              { v: -1, label: "−1 penalize", c: "var(--c-here)" }].map(o => (
              <button key={o.v} className="btn" onClick={() => setSignal(o.v)} style={{
                flex: 1, justifyContent: "center", fontFamily: "var(--f-mono)", fontSize: 12,
                color: signal === o.v ? o.c : "var(--c-ink-dim)",
                borderColor: signal === o.v
                  ? `color-mix(in oklch, ${o.c} 55%, transparent)` : "var(--c-line)",
                background: signal === o.v
                  ? `color-mix(in oklch, ${o.c} 10%, transparent)` : "transparent",
              }}>
                {o.label}
              </button>
            ))}
          </div>
        </div>
      </div>

      <label style={{ display: "block" }}>
        <div className="t-tag" style={{ color: "var(--c-ink-dim)", marginBottom: 4 }}>REASON · REQUIRED</div>
        <textarea value={reason} onChange={e => setReason(e.target.value)}
          placeholder="e.g. escalated a contract-term ambiguity instead of guessing"
          style={{ ...inputStyle, minHeight: 60, resize: "vertical", lineHeight: 1.45 }} />
      </label>

      <label style={{ display: "block" }}>
        <div className="t-tag" style={{ color: "var(--c-ink-dim)", marginBottom: 4 }}>RATER</div>
        <input value={rater} onChange={e => setRater(e.target.value)} style={inputStyle} />
      </label>

      <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", gap: 10 }}>
        <span className="t-mono" style={{ fontSize: 11.5, color: preview >= 0 ? "var(--c-cs)" : "var(--c-here)" }}
              title="signal × 0.2 × (weight[layer] / 0.26)">
          Δ preview {preview >= 0 ? "+" : ""}{preview.toFixed(3)}
        </span>
        <button className="btn primary" disabled={!canSubmit} onClick={submit}
                style={{ opacity: canSubmit ? 1 : 0.5 }}>
          {busy ? "Logging…" : "Log reward ⏎"}
        </button>
      </div>

      {note && (
        <div className="t-cap" style={{
          padding: "7px 10px", borderRadius: "var(--r-md)",
          border: `1px solid color-mix(in oklch, ${
            note.forbidden ? "var(--c-here)"
            : note.offline ? "var(--c-visited)" : "var(--c-cs)"} 45%, transparent)`,
          color: note.forbidden ? "var(--c-here)"
               : note.offline ? "var(--c-visited)" : "var(--c-cs)",
        }}>
          {note.forbidden
            ? "Not logged — this action requires SME or admin role."
            : note.offline
            ? "Backend unreachable — reward held locally and marked unsynced (demo)."
            : "Logged. The record is now part of the append-only audit trail."}
        </div>
      )}
    </div>
  );
}

