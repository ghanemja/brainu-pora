function LicensesCard({ agents }) {
  const [state, setState] = useState("loading"); // loading | live | offline | forbidden
  const [rows, setRows] = useState([]);
  const [note, setNote] = useState(null);       // {kind: ok|forbidden|offline, text}
  const [openId, setOpenId] = useState(null);   // expanded license id
  const [usage, setUsage] = useState({});       // id -> {loading}|{calls,raw}|{error}

  useEffect(() => {
    let dead = false;
    (async () => {
      const api = window.BU_API;
      if (!(api && typeof api.billingLicenses === "function"
            && typeof api.live === "function" && api.live())) {
        if (!dead) setState("offline");
        return;
      }
      try {
        const r = await api.billingLicenses();
        if (dead) return;
        if (r && r.forbidden) { setState("forbidden"); return; }
        if (r && r.offline) { setState("offline"); return; }
        const list = Array.isArray(r) ? r : ((r && (r.licenses || r.rows)) || []);
        setRows(list.map(licNorm));
        setState("live");
      } catch (e) {
        if (!dead) setState(e && e.forbidden ? "forbidden" : "offline");
      }
    })();
    return () => { dead = true; };
  }, []);

  async function toggleUsage(id) {
    if (openId === id) { setOpenId(null); return; }
    setOpenId(id);
    if (usage[id]) return; // cached
    const api = window.BU_API;
    if (!(api && typeof api.billingUsage === "function")) {
      setUsage(u => ({ ...u, [id]: { error: "usage endpoint unavailable" } }));
      return;
    }
    setUsage(u => ({ ...u, [id]: { loading: true } }));
    try {
      const r = await api.billingUsage(id);
      if (r && (r.forbidden || r.offline)) {
        setUsage(u => ({ ...u, [id]: {
          error: r.forbidden ? "requires org admin" : "backend unreachable",
        } }));
        return;
      }
      const calls = r == null ? null
        : (r.calls ?? r.count
           ?? (Array.isArray(r.events) ? r.events.length
               : (Array.isArray(r.usage) ? r.usage.length : null)));
      setUsage(u => ({ ...u, [id]: { calls, raw: r } }));
    } catch (e) {
      setUsage(u => ({ ...u, [id]: { error: (e && e.message) || "usage fetch failed" } }));
    }
  }

  async function revoke(row) {
    const api = window.BU_API;
    if (!(api && typeof api.billingRevoke === "function")) return;
    const reason = window.prompt(
      `Revoke ${row.kind} license for ${agentLabel(row.agentId)} — reason:`, "");
    if (reason == null) return; // cancelled
    let res = null;
    try {
      res = await api.billingRevoke(row.id, reason.trim());
    } catch (e) {
      res = (e && e.forbidden) ? { ok: false, forbidden: true } : { ok: false, offline: true };
    }
    if (res && res.forbidden) {
      setNote({ kind: "forbidden", text: "Not revoked — requires org admin." });
      return;
    }
    if (!res || res.offline || res.ok === false) {
      setNote({ kind: "offline", text: "Backend unreachable — revocation not applied." });
      return;
    }
    setRows(prev => prev.map(r => r.id === row.id
      ? { ...r, status: "revoked", revokedReason: reason.trim(), justRevoked: true }
      : r));
    setNote({ kind: "ok", text: "License revoked — delivery endpoint cut off immediately." });
  }

  const canRevoke = Boolean(window.BU_API && typeof window.BU_API.billingRevoke === "function");
  const offline = state === "offline";

  return (
    <div className="card" style={{ padding: 0, overflow: "hidden" }}>
      <div style={{
        padding: "12px 16px", borderBottom: "1px solid var(--c-line)",
        display: "flex", justifyContent: "space-between", alignItems: "baseline", gap: 12, flexWrap: "wrap",
      }}>
        <div className="t-h3" style={{ display: "flex", gap: 8, alignItems: "baseline" }}>
          License registry
          {offline && (
            <span className="tag" style={{
              color: "var(--c-visited)", fontFamily: "var(--f-mono)", fontSize: 10,
              borderColor: "color-mix(in oklch, var(--c-visited) 50%, transparent)",
            }}>(offline)</span>
          )}
        </div>
        <span className="t-mono" style={{ fontSize: 10.5, color: "var(--c-ink-dim)" }}>
          org-scoped · licenses table · status enforced on every delivery call
        </span>
      </div>

      {note && (
        <div className="t-cap" style={{
          margin: "10px 16px 0", padding: "7px 10px", borderRadius: "var(--r-md)",
          border: `1px solid color-mix(in oklch, ${
            note.kind === "forbidden" ? "var(--c-here)"
            : note.kind === "offline" ? "var(--c-visited)" : "var(--c-cs)"} 45%, transparent)`,
          color: note.kind === "forbidden" ? "var(--c-here)"
               : note.kind === "offline" ? "var(--c-visited)" : "var(--c-cs)",
        }}>{note.text}</div>
      )}

      {state === "loading" && (
        <div className="t-cap" style={{ padding: "14px 16px", color: "var(--c-ink-dim)" }}>
          Loading licenses…
        </div>
      )}

      {state === "forbidden" && (
        <div className="t-cap" style={{ padding: "14px 16px", color: "var(--c-here)" }}>
          Viewing the license registry requires org admin.
        </div>
      )}

      {offline && <LicensesSeed agents={agents} />}

      {state === "live" && (
        <div style={{ overflowX: "auto" }}>
          <div style={{ minWidth: 860 }}>
            <div className="t-tag" style={{
              display: "grid", gridTemplateColumns: LIC_COLS, gap: 10,
              padding: "9px 16px", color: "var(--c-ink-dim)",
              borderBottom: "1px solid var(--c-line-strong)",
            }}>
              <span>AGENT</span><span>KIND</span><span>STATUS</span>
              <span>CREATED</span><span>EXPIRES</span><span>USAGE</span><span />
            </div>
            {rows.length === 0 && (
              <div className="t-cap" style={{ padding: "14px 16px", color: "var(--c-ink-dim)" }}>
                No licenses issued yet — the first key comes from the Marketplace License button.
              </div>
            )}
            {rows.map((r, i) => {
              const revoked = r.status === "revoked";
              const u = usage[r.id];
              return (
                <React.Fragment key={r.id || i}>
                  <div style={{
                    display: "grid", gridTemplateColumns: LIC_COLS, gap: 10,
                    padding: "8px 16px", alignItems: "baseline", fontSize: 12.5,
                    borderBottom: openId === r.id ? "none" : "1px solid var(--c-line)",
                    background: revoked
                      ? "color-mix(in oklch, var(--c-here) 6%, transparent)"
                      : i % 2 ? "color-mix(in oklch, var(--c-bg-elev-2) 40%, transparent)" : "transparent",
                    opacity: revoked ? 0.85 : 1,
                  }}>
                    <span style={{ overflow: "hidden", textOverflow: "ellipsis", whiteSpace: "nowrap" }}>
                      {agentLabel(r.agentId)}
                    </span>
                    <span className="t-mono" style={{ fontSize: 11 }}>{r.kind}</span>
                    <LicStatusChip status={r.status} />
                    <span className="t-mono" style={{ fontSize: 11, color: "var(--c-ink-muted)" }}>
                      {licTs(r.created)}
                    </span>
                    <span className="t-mono" style={{ fontSize: 11, color: "var(--c-ink-muted)" }}>
                      {licTs(r.expires)}
                    </span>
                    <button className="btn ghost" style={{ fontSize: 10.5, padding: "2px 7px", justifySelf: "start" }}
                      onClick={() => toggleUsage(r.id)}>
                      {openId === r.id ? "▾ usage" : "▸ usage"}
                    </button>
                    {revoked ? (
                      <span className="t-mono" style={{ fontSize: 10, color: "var(--c-here)" }}>⨯ revoked</span>
                    ) : canRevoke ? (
                      <button className="btn ghost" style={{
                        fontSize: 10.5, padding: "2px 7px", color: "var(--c-here)", justifySelf: "start",
                      }} onClick={() => revoke(r)}>
                        revoke
                      </button>
                    ) : <span />}
                  </div>
                  {openId === r.id && (
                    <div className="t-mono" style={{
                      padding: "4px 16px 10px", fontSize: 11, color: "var(--c-ink-muted)",
                      borderBottom: "1px solid var(--c-line)",
                      background: revoked ? "color-mix(in oklch, var(--c-here) 6%, transparent)" : "transparent",
                    }}>
                      {!u || u.loading ? "loading usage…"
                        : u.error ? <span style={{ color: "var(--c-here)" }}>{u.error}</span>
                        : `${u.calls != null ? u.calls : "—"} metered call${u.calls === 1 ? "" : "s"} (usage_events)`
                          + (u.raw && u.raw.tokensIn != null
                             ? ` · ${u.raw.tokensIn} tok in / ${u.raw.tokensOut} tok out` : "")}
                      {r.revokedReason && (
                        <span style={{ color: "var(--c-here)", marginLeft: 12 }}>
                          revoked: {r.revokedReason}
                        </span>
                      )}
                      {r.justRevoked && (
                        <span style={{ color: "var(--c-here)", marginLeft: 12 }}>
                          · delivery endpoint cut off immediately
                        </span>
                      )}
                    </div>
                  )}
                  {r.justRevoked && openId !== r.id && (
                    <div className="t-mono" style={{
                      padding: "2px 16px 8px", fontSize: 10.5, color: "var(--c-here)",
                      borderBottom: "1px solid var(--c-line)",
                      background: "color-mix(in oklch, var(--c-here) 6%, transparent)",
                    }}>
                      delivery endpoint cut off immediately — the gate checks status on every call
                    </div>
                  )}
                </React.Fragment>
              );
            })}
          </div>
        </div>
      )}
    </div>
  );
}

// ── Exhibit 3a: reward-weight bar chart (inline SVG) ─────────────
function RewardWeightChart({ weights }) {
  const entries = [1, 2, 3, 4, 5, 6, 7].map(n => ({ n, w: Number(weights["L" + n]) || 0 }));
  const max = Math.max(0.01, ...entries.map(e => e.w));
  const heavyShare = entries.slice(4).reduce((s, e) => s + e.w, 0);

  const W = 560, H = 240;
  const padL = 30, padR = 14, padT = 48, padB = 30;
  const innerW = W - padL - padR, innerH = H - padT - padB;
  const step = innerW / entries.length;
  const barW = Math.min(44, step * 0.6);
  const baseY = H - padB;
  const xOf = i => padL + i * step + (step - barW) / 2;

  const regionX = padL + 4 * step + 3;
  const regionW = 3 * step - 6;

  return (
    <svg viewBox={`0 0 ${W} ${H}`} style={{ width: "100%", height: "auto", display: "block" }}
         role="img" aria-label="RL reward weights by layer — L5 to L7 carry most of the reward mass">
      {/* company-layers emphasis region behind L5–L7 */}
      <rect x={regionX} y={padT - 16} width={regionW} height={innerH + 16}
            rx="6" fill={GOLD} fillOpacity="0.07"
            stroke={GOLD} strokeOpacity="0.35" strokeDasharray="3 4" strokeWidth="1" />
      <text x={regionX + regionW / 2} y={padT - 24} textAnchor="middle"
            fontSize="10" fontFamily="var(--f-mono)" fill={GOLD} letterSpacing="0.08em">
        L5–L7 · {Math.round(heavyShare * 100)}% OF REWARD MASS
      </text>

      {/* bars */}
      {entries.map((e, i) => {
        const h = (e.w / max) * innerH;
        const y = baseY - h;
        return (
          <g key={e.n}>
            <rect x={xOf(i)} y={y} width={barW} height={h} rx="3"
                  fill={layerColor(e.n)} fillOpacity={e.n >= 5 ? 0.92 : 0.55}>
              <title>{`L${e.n} — weight ${e.w}`}</title>
            </rect>
            <text x={xOf(i) + barW / 2} y={y - 6} textAnchor="middle"
                  fontSize="10" fontFamily="var(--f-mono)" fill="var(--c-ink-muted)">
              {e.w.toFixed(2)}
            </text>
            <text x={xOf(i) + barW / 2} y={H - 12} textAnchor="middle"
                  fontSize="10" fontFamily="var(--f-mono)" fill={layerColor(e.n)}>
              L{e.n}
            </text>
          </g>
        );
      })}

      {/* baseline */}
      <line x1={padL} y1={baseY} x2={W - padR} y2={baseY}
            stroke="var(--c-line-strong)" strokeWidth="1" />
    </svg>
  );
}

// ── Exhibit 3b: log-human-reward form ────────────────────────────
function HitlForm({ agents, weights, onSubmit }) {
  const first = agents[0] || null;
  const [agentId, setAgentId] = useState(first ? first.id : "");
  const [layer, setLayer] = useState(first ? first.level : 5);
  const [signal, setSignal] = useState(1);
  const [reason, setReason] = useState("");
  const [rater, setRater] = useState("human-reviewer");
  const [busy, setBusy] = useState(false);
  const [note, setNote] = useState(null); // {offline:bool, forbidden:bool}

  const w = Number(weights["L" + layer]) || 0;
  const preview = signal * 0.2 * (w / 0.26);
  const canSubmit = agentId && reason.trim() && !busy;

  const handleAgent = id => {
    setAgentId(id);
    const a = agents.find(x => x.id === id);
    if (a && a.level) setLayer(a.level);
  };

  const submit = async () => {
    if (!canSubmit) return;
    setBusy(true);
    setNote(null);
    const res = await onSubmit({
      agentId, layer, signal, reason: reason.trim(), rater: rater.trim() || "human-reviewer",
    });
    setBusy(false);
    setNote(res);
    // Keep the typed reason when the submit was refused for role — the
    // rater may re-submit after switching to an SME/admin session.
    if (!(res && res.forbidden)) setReason("");
  };

  return (
    <div className="card" style={{ padding: 18, display: "flex", flexDirection: "column", gap: 12 }}>
      <div>
        <div className="t-tag" style={{ color: GOLD, marginBottom: 4 }}>LOG HUMAN REWARD</div>
        <div className="t-cap" style={{ lineHeight: 1.5 }}>
          One judgment, one record. Your signal is weighted by layer, appended to the
          audit log, and folded into the agent's reinforcement.
        </div>
      </div>

      <label style={{ display: "block" }}>
        <div className="t-tag" style={{ color: "var(--c-ink-dim)", marginBottom: 4 }}>AGENT</div>
        <select value={agentId} onChange={e => handleAgent(e.target.value)} style={inputStyle}>
          {agents.map(a => (
            <option key={a.id} value={a.id}>
              {a.name} — L{a.level} · {a.tier}
            </option>
          ))}
        </select>
      </label>

      <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: 10 }}>
        <label style={{ display: "block" }}>
          <div className="t-tag" style={{ color: "var(--c-ink-dim)", marginBottom: 4 }}>LAYER</div>
          <select value={layer} onChange={e => setLayer(+e.target.value)} style={inputStyle}>
            {[1, 2, 3, 4, 5, 6, 7].map(n => (
              <option key={n} value={n}>
                L{n} · weight {(Number(weights["L" + n]) || 0).toFixed(2)}
              </option>
            ))}
          </select>
        </label>
        <div>
          <div className="t-tag" style={{ color: "var(--c-ink-dim)", marginBottom: 4 }}>SIGNAL</div>
          <div style={{ display: "flex", gap: 6 }}>
            {[{ v: 1, label: "+1 reinforce", c: "var(--c-cs)" },
              { v: -1, label: "−1 penalize", c: "var(--c-here)" }].map(o => (
              <button key={o.v} className="btn" onClick={() => setSignal(o.v)} style={{
                flex: 1, justifyContent: "center", fontFamily: "var(--f-mono)", fontSize: 12,
                color: signal === o.v ? o.c : "var(--c-ink-dim)",
                borderColor: signal === o.v
                  ? `color-mix(in oklch, ${o.c} 55%, transparent)` : "var(--c-line)",
                background: signal === o.v
                  ? `color-mix(in oklch, ${o.c} 10%, transparent)` : "transparent",
              }}>
                {o.label}
              </button>
            ))}
          </div>
        </div>
      </div>

      <label style={{ display: "block" }}>
        <div className="t-tag" style={{ color: "var(--c-ink-dim)", marginBottom: 4 }}>REASON · REQUIRED</div>
        <textarea value={reason} onChange={e => setReason(e.target.value)}
          placeholder="e.g. escalated a contract-term ambiguity instead of guessing"
          style={{ ...inputStyle, minHeight: 60, resize: "vertical", lineHeight: 1.45 }} />
      </label>

      <label style={{ display: "block" }}>
        <div className="t-tag" style={{ color: "var(--c-ink-dim)", marginBottom: 4 }}>RATER</div>
        <input value={rater} onChange={e => setRater(e.target.value)} style={inputStyle} />
      </label>

      <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", gap: 10 }}>
        <span className="t-mono" style={{ fontSize: 11.5, color: preview >= 0 ? "var(--c-cs)" : "var(--c-here)" }}
              title="signal × 0.2 × (weight[layer] / 0.26)">
          Δ preview {preview >= 0 ? "+" : ""}{preview.toFixed(3)}
        </span>
        <button className="btn primary" disabled={!canSubmit} onClick={submit}
                style={{ opacity: canSubmit ? 1 : 0.5 }}>
          {busy ? "Logging…" : "Log reward ⏎"}
        </button>
      </div>

      {note && (
        <div className="t-cap" style={{
          padding: "7px 10px", borderRadius: "var(--r-md)",
          border: `1px solid color-mix(in oklch, ${
            note.forbidden ? "var(--c-here)"
            : note.offline ? "var(--c-visited)" : "var(--c-cs)"} 45%, transparent)`,
          color: note.forbidden ? "var(--c-here)"
               : note.offline ? "var(--c-visited)" : "var(--c-cs)",
        }}>
          {note.forbidden
            ? "Not logged — this action requires SME or admin role."
            : note.offline
            ? "Backend unreachable — reward held locally and marked unsynced (demo)."
            : "Logged. The record is now part of the append-only audit trail."}
        </div>
      )}
    </div>
  );
}

