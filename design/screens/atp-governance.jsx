function findAgent(id) {
  const d = window.ATP_DATA;
  if (!d) return null;
  if (typeof d.agentById === "function") return d.agentById(id) || null;
  return (d.AGENTS || []).find(a => a.id === id) || null;
}

function agentLabel(id) {
  const a = findAgent(id);
  return a ? `${a.emoji ? a.emoji + " " : ""}${a.name}` : id;
}

// Normalize a log row's layer field (seed may carry 5 or "L5").
function layerN(v) {
  if (typeof v === "number") return v;
  const m = String(v || "").match(/\d+/);
  return m ? +m[0] : null;
}

