// ── Small agent chip (revoked flagged) ───────────────────────────
function AgentChip({ id }) {
  const a = findAgent(id);
  if (!a) return <span className="tag">{id}</span>;
  const revoked = a.status === "revoked";
  return (
    <span className="tag" title={`${a.name} · L${a.level} · ${a.status}`} style={{
      color: revoked ? "var(--c-here)" : "var(--c-ink)",
      borderColor: revoked
        ? "color-mix(in oklch, var(--c-here) 50%, transparent)"
        : "var(--c-line-strong)",
    }}>
      {a.emoji} {a.name}
      <span style={{ color: layerColor(a.level), fontFamily: "var(--f-mono)" }}> L{a.level}</span>
      {revoked && " ⨯"}
    </span>
  );
}

