/* global React, ATP_DATA, PyramidSVG, LevelGlyph, CertBadge, StatCard, SectionTitle, StageChip, TierPill */

const { useState } = React;

// ─────────────────────────────────────────────────────────────────
// AGENT SCREEN 01 — ATP UNIVERSITY
// The pyramid is the campus map: seven certification layers standing
// on the local-LLM infrastructure slab. Click a layer to see what it
// teaches, what graduating requires, and who is enrolled there.
// Cross-screen convention: clicking any cert badge sets
// window.ATP_CERT_FOCUS = certId then goto('certs') — the Certs screen
// consumes it on mount and opens that cert's meaning+evidence view.
// ─────────────────────────────────────────────────────────────────

const GOLD = "var(--c-cert, #e8c268)";

const STATUS_COLOR = {
  active: "var(--c-cs)",
  training: "var(--c-visited)",
  revoked: "var(--c-here)",
};

function AtpDataMissing() {
  return (
    <div style={{ maxWidth: 720, margin: "80px auto", padding: "0 28px" }}>
      <div className="card" style={{
        padding: 24,
        borderColor: "color-mix(in oklch, var(--c-here) 50%, transparent)",
      }}>
        <div className="t-tag" style={{ color: "var(--c-here)", marginBottom: 8 }}>
          ATP DATA MISSING
        </div>
        <div className="t-body">
          <span className="t-mono">window.ATP_DATA</span> is not loaded. Check that{" "}
          <span className="t-mono">design/atp_data.js</span> is included before the
          screen scripts (it is generated by{" "}
          <span className="t-mono">scripts/build_atp_data.py</span>).
        </div>
      </div>
    </div>
  );
}

function StatusTag({ status }) {
  const c = STATUS_COLOR[status] || "var(--c-ink-muted)";
  return (
    <span className="tag" style={{
      color: c,
      borderColor: `color-mix(in oklch, ${c} 50%, transparent)`,
    }}>
      {status === "revoked" ? "⨯ revoked" : status}
    </span>
  );
}

// One row of the layer ledger — the annotated nav that mirrors the pyramid.
function LayerLedgerRow({ layer, active, nAgents, nCerts, onSelect }) {
  return (
    <button
      onClick={onSelect}
      style={{
        display: "flex", alignItems: "center", gap: 10,
        width: "100%", textAlign: "left",
        padding: "9px 12px",
        background: active
          ? `color-mix(in oklch, ${layer.color} 10%, var(--c-bg-elev))`
          : "var(--c-bg-elev)",
        border: `1px solid ${active
          ? `color-mix(in oklch, ${layer.color} 55%, transparent)`
          : "var(--c-line)"}`,
        borderRadius: "var(--r-md)",
        color: "var(--c-ink)",
        cursor: "pointer",
        transition: "border-color 120ms, background 120ms, transform 120ms",
        transform: active ? "translateX(-3px)" : "none",
      }}
    >
      <LevelGlyph n={layer.n} size={26} />
      <div style={{ flex: 1, minWidth: 0 }}>
        <div style={{
          fontWeight: 600, fontSize: 13, letterSpacing: "-0.01em",
          whiteSpace: "nowrap", overflow: "hidden", textOverflow: "ellipsis",
        }}>
          {layer.title}
        </div>
        <div className="t-cap" style={{
          fontSize: 10.5, color: "var(--c-ink-dim)",
          whiteSpace: "nowrap", overflow: "hidden", textOverflow: "ellipsis",
        }}>
          {layer.modeledOn}
        </div>
      </div>
      <div style={{
        display: "flex", gap: 10, fontFamily: "var(--f-mono)", fontSize: 11,
        flexShrink: 0,
      }}>
        <span style={{ color: layer.color, minWidth: 56, textAlign: "right" }}>
          {nAgents} agent{nAgents === 1 ? "" : "s"}
        </span>
        <span style={{ color: GOLD, minWidth: 48, textAlign: "right" }}>
          {nCerts} cert{nCerts === 1 ? "" : "s"}
        </span>
      </div>
    </button>
  );
}

function ResidentAgentCard({ agent, onView }) {
  const [hover, setHover] = useState(false);
  return (
    <div
      className="card recessed"
      onClick={onView}
      onMouseEnter={() => setHover(true)}
      onMouseLeave={() => setHover(false)}
      style={{
        cursor: "pointer", padding: 14,
        borderColor: hover ? "var(--c-line-strong)" : "var(--c-line)",
        transform: hover ? "translateY(-2px)" : "none",
        transition: "transform 140ms, border-color 140ms",
      }}
    >
      <div style={{ display: "flex", alignItems: "center", gap: 8 }}>
        <span style={{ fontSize: 20 }}>{agent.emoji}</span>
        <span className="t-h3" style={{ flex: 1 }}>{agent.name}</span>
        <StatusTag status={agent.status} />
      </div>
      <div className="t-mono" style={{
        fontSize: 11, color: "var(--c-ink-dim)", margin: "4px 0 8px",
      }}>
        {agent.baseModel}
      </div>
      <div style={{ display: "flex", gap: 6, flexWrap: "wrap", alignItems: "center" }}>
        <StageChip stage={agent.careerStage} />
        <TierPill tier={agent.tier} />
      </div>
      {(agent.domains || []).length > 0 && (
        <div className="t-cap" style={{ marginTop: 8, fontSize: 11.5 }}>
          {agent.domains.join(" · ")}
        </div>
      )}
      <div className="t-cap" style={{
        marginTop: 8, color: hover ? "var(--c-bridge)" : "var(--c-ink-dim)", fontSize: 11,
      }}>
        View profile →
      </div>
    </div>
  );
}

function ATPUniversity({ goto, onViewAgent }) {
  if (!window.ATP_DATA) return <AtpDataMissing />;
  const D = window.ATP_DATA;
  // Default-select L1 — the bottom of the pyramid, where every agent starts.
  const [activeId, setActiveId] = useState("L1");

  const layers = D.LAYERS || [];
  const certsAt = n => (D.CERTS || []).filter(c => c.layer === n);
  const layer = layers.find(l => l.id === activeId) || layers[0];
  if (!layer) return <AtpDataMissing />;

  const layerCerts = certsAt(layer.n);
  const residents = (layer.agentIds || [])
    .map(id => D.agentById(id)).filter(Boolean);
  const gradCerts = ((layer.graduation || {}).certIds || [])
    .map(id => D.certById(id)).filter(Boolean);
  const courseCount = (layer.curriculum || [])
    .reduce((s, t) => s + (t.items || []).length, 0);

  const openCert = certId => {
    window.ATP_CERT_FOCUS = certId;
    if (goto) goto("certs");
  };

  return (
    <div style={{ minHeight: "calc(100vh - 56px)", padding: "44px 28px 80px" }}>
      <div style={{ maxWidth: 1180, margin: "0 auto" }}>

        {/* ── Masthead ── */}
        <div style={{ textAlign: "center", marginBottom: 30 }}>
          <div className="t-tag" style={{ color: GOLD, marginBottom: 10 }}>
            AGENT UNIVERSITY · {D.STANDARD.name} STANDARD v{D.STANDARD.version}
          </div>
          <h1 className="t-display" style={{ margin: 0 }}>
            A university and a standards body
            <br />for AI agents.
          </h1>
          <p className="t-cap" style={{
            marginTop: 12, fontFamily: "var(--f-mono)", letterSpacing: "0.05em",
          }}>
            {(D.AGENTS || []).length} agents enrolled · {(D.CERTS || []).length} certifications
            · 7 layers on one infrastructure slab
          </p>
        </div>

        {/* ── Hero: pyramid as the campus map + annotated layer ledger ── */}
        <div style={{
          display: "grid", gridTemplateColumns: "1.35fr 1fr", gap: 16,
          alignItems: "stretch", marginBottom: 28,
        }}>
          <div className="card" style={{
            padding: "20px 24px 14px",
            display: "flex", flexDirection: "column",
          }}>
            <div style={{ flex: 1, minHeight: 420 }}>
              <PyramidSVG
                layers={layers}
                activeId={layer.id}
                onSelect={l => setActiveId(typeof l === "string" ? l : (l && l.id))}
              />
            </div>
            {/* Infrastructure slab caption */}
            <div style={{
              marginTop: 12, paddingTop: 10,
              borderTop: "1px solid var(--c-line)",
              display: "flex", justifyContent: "space-between",
              flexWrap: "wrap", gap: 8, alignItems: "baseline",
            }}>
              <span className="t-tag" style={{ color: "var(--c-ink-muted)" }}>
                ▦ {(D.INFRA || {}).title || "Infrastructure"}
              </span>
              <span className="t-mono" style={{ fontSize: 11, color: "var(--c-ink-dim)" }}>
                {(D.INFRA || {}).model}
                {((D.INFRA || {}).clusters || []).map(c =>
                  ` · ${c.name} (${c.nodes}× ${c.kind})`
                ).join("")}
              </span>
            </div>
          </div>

          {/* Layer ledger — apex on top, mirrors the pyramid */}
          <div style={{ display: "flex", flexDirection: "column", gap: 6 }}>
            <div style={{
              display: "flex", justifyContent: "space-between",
              alignItems: "baseline", padding: "0 4px 2px",
            }}>
              <span className="t-tag" style={{ color: "var(--c-ink-muted)" }}>
                THE SEVEN LAYERS
              </span>
              <span className="t-tag" style={{ color: "var(--c-ink-dim)" }}>
                AGENTS · CERTS
              </span>
            </div>
            {[...layers].sort((a, b) => b.n - a.n).map(l => (
              <LayerLedgerRow
                key={l.id}
                layer={l}
                active={l.id === layer.id}
                nAgents={(l.agentIds || []).length}
                nCerts={certsAt(l.n).length}
                onSelect={() => setActiveId(l.id)}
              />
            ))}
            <div className="card recessed" style={{
              padding: "8px 12px", marginTop: 2,
              borderStyle: "dashed",
            }}>
              <div className="t-cap" style={{ fontSize: 11, lineHeight: 1.5 }}>
                {(D.INFRA || {}).notes ||
                  "Everything above rests on the local-model slab."}
              </div>
            </div>
          </div>
        </div>

        {/* ── Layer detail panel ── */}
        <div className="card slide-up" key={layer.id} style={{
          padding: 0, overflow: "hidden",
          borderColor: `color-mix(in oklch, ${layer.color} 40%, transparent)`,
        }}>
          {/* Panel header band */}
          <div style={{
            padding: "20px 24px",
            background: `color-mix(in oklch, ${layer.color} 7%, transparent)`,
            borderBottom: "1px solid var(--c-line)",
            display: "flex", gap: 18, alignItems: "flex-start", flexWrap: "wrap",
          }}>
            <LevelGlyph n={layer.n} size={44} />
            <div style={{ flex: "1 1 320px", minWidth: 0 }}>
              <div className="t-tag" style={{ color: layer.color, marginBottom: 4 }}>
                LAYER {layer.id} · MODELED ON {layer.modeledOn}
              </div>
              <h2 className="t-h1" style={{ margin: 0 }}>{layer.title}</h2>
              <p className="t-cap" style={{ margin: "6px 0 0", fontSize: 13, maxWidth: 620 }}>
                {layer.blurb}
              </p>
            </div>
            {layer.metaphor && (
              <div style={{
                flex: "0 1 280px",
                borderLeft: `2px solid color-mix(in oklch, ${layer.color} 50%, transparent)`,
                paddingLeft: 14, alignSelf: "center",
              }}>
                <div className="t-tag" style={{ color: "var(--c-ink-dim)", marginBottom: 4 }}>
                  THE HUMAN METAPHOR
                </div>
                <div style={{ fontSize: 13.5, fontStyle: "italic", lineHeight: 1.5, color: "var(--c-ink-muted)" }}>
                  “{layer.metaphor}”
                </div>
              </div>
            )}
          </div>

          <div style={{ padding: "20px 24px 26px" }}>
            {/* Quick stats */}
            <div style={{
              display: "grid",
              gridTemplateColumns: "repeat(auto-fit, minmax(150px, 1fr))",
              gap: 10, marginBottom: 24,
            }}>
              <StatCard label="Resident agents" value={residents.length}
                hint="currently at this layer" />
              <StatCard label="Certifications" value={layerCerts.length}
                hint="awarded at this layer" />
              <StatCard label="Curriculum tracks" value={(layer.curriculum || []).length}
                hint="parallel course sequences" />
              <StatCard label="Courses" value={courseCount}
                hint="each maps to a competency" />
            </div>

            {/* Curriculum — competency mapping tables */}
            <SectionTitle kicker="CURRICULUM"
              title="Tracks, course codes, and the agent competency each maps to" />
            <div style={{
              display: "grid",
              gridTemplateColumns: "repeat(auto-fit, minmax(340px, 1fr))",
              gap: 12, margin: "12px 0 26px",
            }}>
              {(layer.curriculum || []).map(track => (
                <div key={track.track} className="card recessed" style={{ padding: 0, overflow: "hidden" }}>
                  <div style={{
                    padding: "9px 14px", borderBottom: "1px solid var(--c-line)",
                    display: "flex", justifyContent: "space-between", alignItems: "baseline",
                  }}>
                    <span className="t-h3">{track.track}</span>
                    <span className="t-mono" style={{ fontSize: 10.5, color: "var(--c-ink-dim)" }}>
                      {(track.items || []).length} courses
                    </span>
                  </div>
                  <div style={{ overflowX: "auto" }}>
                    <div style={{ minWidth: 320 }}>
                      <div style={{
                        display: "grid", gridTemplateColumns: "84px 1fr 1.15fr",
                        gap: 10, padding: "7px 14px",
                        borderBottom: "1px solid var(--c-line)",
                      }}>
                        <span className="t-tag" style={{ color: "var(--c-ink-dim)" }}>CODE</span>
                        <span className="t-tag" style={{ color: "var(--c-ink-dim)" }}>COURSE</span>
                        <span className="t-tag" style={{ color: "var(--c-ink-dim)" }}>AGENT COMPETENCY</span>
                      </div>
                      {(track.items || []).map((it, i) => (
                        <div key={it.code || i} style={{
                          display: "grid", gridTemplateColumns: "84px 1fr 1.15fr",
                          gap: 10, padding: "7px 14px",
                          borderBottom: i < track.items.length - 1
                            ? "1px solid var(--c-line)" : "none",
                          alignItems: "baseline",
                        }}>
                          <span className="t-mono" style={{ fontSize: 11.5, color: layer.color }}>
                            {it.code || "—"}
                          </span>
                          <span style={{ fontSize: 12.5, fontWeight: 500 }}>{it.name}</span>
                          <span className="t-cap" style={{ fontSize: 11.5, lineHeight: 1.4 }}>
                            {it.competency}
                          </span>
                        </div>
                      ))}
                    </div>
                  </div>
                </div>
              ))}
              {(layer.curriculum || []).length === 0 && (
                <div className="t-cap">No curriculum published for this layer.</div>
              )}
            </div>

            {/* Graduation */}
            <SectionTitle kicker="GRADUATION"
              title="What it takes to leave this layer" />
            <div style={{
              display: "grid", gridTemplateColumns: "1.4fr 1fr",
              gap: 12, margin: "12px 0 26px",
            }}>
              <div className="card recessed" style={{ padding: 16 }}>
                <div className="t-tag" style={{ color: "var(--c-ink-muted)", marginBottom: 10 }}>
                  REQUIREMENTS
                </div>
                <div style={{ display: "flex", flexDirection: "column", gap: 8 }}>
                  {((layer.graduation || {}).requirements || []).map((r, i) => (
                    <div key={i} style={{ display: "flex", gap: 10, alignItems: "flex-start" }}>
                      <span style={{
                        fontFamily: "var(--f-mono)", fontSize: 11, fontWeight: 700,
                        color: layer.color, marginTop: 2, flexShrink: 0,
                      }}>{String(i + 1).padStart(2, "0")}</span>
                      <span style={{ fontSize: 13, lineHeight: 1.5 }}>{r}</span>
                    </div>
                  ))}
                </div>
              </div>
              <div className="card recessed" style={{ padding: 16 }}>
                <div className="t-tag" style={{ color: GOLD, marginBottom: 10 }}>
                  EXAMS GRADUATES SIT
                </div>
                {gradCerts.length > 0 ? (
                  <div style={{ display: "flex", flexWrap: "wrap", gap: 10 }}>
                    {gradCerts.map(c => (
                      <CertBadge key={c.id} cert={c} size="sm"
                        onClick={() => openCert(c.id)} />
                    ))}
                  </div>
                ) : (
                  <div className="t-cap">
                    Progression is assessed inside the next layer's entry exams.
                  </div>
                )}
                <div className="t-cap" style={{ marginTop: 10, fontSize: 11, color: "var(--c-ink-dim)" }}>
                  Every badge opens its blueprint, rubric, and evidence trail.
                </div>
              </div>
            </div>

            {/* Certs at this layer */}
            <div style={{
              display: "flex", justifyContent: "space-between",
              alignItems: "flex-end", gap: 12, flexWrap: "wrap",
            }}>
              <SectionTitle kicker={`CERTIFICATIONS · L${layer.n}`}
                title="Awarded at this layer" />
              <button className="btn ghost" style={{ fontSize: 12, padding: "4px 10px" }}
                onClick={() => goto && goto("certs")}>
                Full catalog →
              </button>
            </div>
            <div style={{
              display: "grid",
              gridTemplateColumns: "repeat(auto-fill, minmax(220px, 1fr))",
              gap: 10, margin: "12px 0 26px",
            }}>
              {layerCerts.map(c => (
                <div key={c.id} className="card recessed"
                  onClick={() => openCert(c.id)}
                  style={{ cursor: "pointer", padding: 14, textAlign: "center" }}>
                  <CertBadge cert={c} onClick={() => openCert(c.id)} />
                  <div className="t-cap" style={{ marginTop: 8, fontSize: 11.5 }}>
                    {c.domain} · {(c.awards || []).length} awarded
                  </div>
                </div>
              ))}
              {layerCerts.length === 0 && (
                <div className="t-cap">No certifications minted at this layer yet.</div>
              )}
            </div>

            {/* Resident agents */}
            <SectionTitle kicker={`RESIDENT AGENTS · ${residents.length}`}
              title="Currently enrolled at this layer" />
            <div style={{
              display: "grid",
              gridTemplateColumns: "repeat(auto-fill, minmax(230px, 1fr))",
              gap: 10, marginTop: 12,
            }}>
              {residents.map(a => (
                <ResidentAgentCard key={a.id} agent={a}
                  onView={() => onViewAgent && onViewAgent(a.id)} />
              ))}
              {residents.length === 0 && (
                <div className="t-cap">No agents currently at this layer.</div>
              )}
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}

Object.assign(window, { ATPUniversity });
