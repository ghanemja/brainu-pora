"""
Manim renderer — SceneSpec → Manim Community Edition Python script → mp4.

Consumes the same SceneSpec produced by agents.animation_script.

Requires Manim CE installed (`pip install manim`) + LaTeX + ffmpeg.
Falls back gracefully: if Manim or LaTeX not available, returns None and
the frontend should use the browser SVG renderer instead.

Public:
  emit_py(scene, out_path) -> Path         write Manim script to disk
  render(scene, force=False) -> Path | None    write + invoke `manim` CLI
"""

from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
from pathlib import Path

PROJECT_ROOT = Path(__file__).parent.parent
RENDER_DIR = PROJECT_ROOT / "data" / "sessions" / "animations"
RENDER_DIR.mkdir(parents=True, exist_ok=True)


def manim_available() -> bool:
    return shutil.which("manim") is not None


def render(scene: dict, quality: str = "m", force: bool = False) -> Path | None:
    """SceneSpec → mp4. Returns Path or None if Manim missing."""
    if not manim_available():
        return None
    key = _key(scene)
    out_mp4 = RENDER_DIR / f"manim_{key}.mp4"
    if out_mp4.exists() and not force:
        return out_mp4

    py_path = RENDER_DIR / f"manim_{key}.py"
    emit_py(scene, py_path)

    # manim CLI: -q m (medium quality), -o name
    cmd = [
        "manim", "-q", quality,
        "--media_dir", str(RENDER_DIR),
        "-o", f"manim_{key}.mp4",
        str(py_path), "BrainUScene",
    ]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=600)
    except (subprocess.TimeoutExpired, FileNotFoundError):
        return None
    if proc.returncode != 0:
        # write logs for debugging — caller can check
        (RENDER_DIR / f"manim_{key}.log").write_text(
            (proc.stdout or "") + "\n--- STDERR ---\n" + (proc.stderr or "")
        )
        return None

    # manim drops output under media_dir/videos/<py_stem>/<quality>p<fps>/...
    # walk and copy / symlink to predictable location
    found = _find_manim_output(RENDER_DIR, key)
    if found and found.exists():
        try:
            shutil.copy(found, out_mp4)
        except Exception:
            return found
        return out_mp4
    return None


def emit_py(scene: dict, out_path: Path) -> Path:
    """Write a Manim CE Python file for the given SceneSpec."""
    lines = [
        "# Auto-generated by agents.manim_renderer — do not edit by hand",
        "from manim import *",
        "",
        "class BrainUScene(Scene):",
        "    def construct(self):",
        f"        # {scene.get('title', '')}",
    ]
    for i, beat in enumerate(scene.get("beats", [])):
        kind = beat.get("kind")
        dur = float(beat.get("duration_s") or 3.0)
        payload = beat.get("payload", {})
        if kind == "title":
            text = _q(payload.get("text", ""))
            lines += [
                f"        t{i} = Text({text}, font_size=48)",
                f"        self.play(Write(t{i}))",
                f"        self.wait({dur:.2f})",
                f"        self.play(FadeOut(t{i}))",
            ]
        elif kind == "equation":
            latex = _q(payload.get("latex", ""))
            lines += [
                f"        eq{i} = MathTex({latex})",
                f"        self.play(Write(eq{i}))",
                f"        self.wait({dur:.2f})",
                f"        self.play(FadeOut(eq{i}))",
            ]
        elif kind == "transform_eq":
            a = _q(payload.get("from_latex", ""))
            b = _q(payload.get("to_latex", ""))
            label = _q(payload.get("label", ""))
            lines += [
                f"        a{i} = MathTex({a})",
                f"        b{i} = MathTex({b})",
                f"        lbl{i} = Text({label}, font_size=24).to_edge(DOWN)",
                f"        self.play(Write(a{i}))",
                f"        self.wait(0.6)",
                f"        self.play(TransformMatchingTex(a{i}, b{i}), Write(lbl{i}))",
                f"        self.wait({dur:.2f})",
                f"        self.play(FadeOut(b{i}), FadeOut(lbl{i}))",
            ]
        elif kind == "callout":
            text = _q(payload.get("text", ""))
            lines += [
                f"        c{i} = Text({text}, font_size=36, color=YELLOW)",
                f"        self.play(FadeIn(c{i}, shift=UP))",
                f"        self.wait({dur:.2f})",
                f"        self.play(FadeOut(c{i}))",
            ]
        elif kind == "vector_field":
            vecs = payload.get("vectors", [])[:24]
            lines.append(f"        vg{i} = VGroup()")
            for j, v in enumerate(vecs):
                vx = float(v.get("dx", 1)); vy = float(v.get("dy", 0))
                ox = float(v.get("x", 0));  oy = float(v.get("y", 0))
                lines.append(
                    f"        vg{i}.add(Arrow(start=[{ox:.2f},{oy:.2f},0], "
                    f"end=[{ox+vx:.2f},{oy+vy:.2f},0], buff=0))"
                )
            lines += [
                f"        self.play(Create(vg{i}))",
                f"        self.wait({dur:.2f})",
                f"        self.play(FadeOut(vg{i}))",
            ]
        elif kind == "graph_plot":
            xs_ys = []
            for c in (payload.get("curves") or [])[:3]:
                pts = c.get("points", [])
                if pts:
                    xs_ys.append((c.get("name", ""), pts))
            if xs_ys:
                lines.append(f"        ax{i} = Axes(x_range=[0, 10], y_range=[0, 10])")
                lines.append(f"        self.play(Create(ax{i}))")
                for name, pts in xs_ys:
                    xs = [float(p[0]) for p in pts]
                    pf = "[" + ",".join(f"({x:.2f},{y:.2f})" for x, y in pts) + "]"
                    lines.append(
                        f"        curve = ax{i}.plot_line_graph(x_values={xs}, y_values={[p[1] for p in pts]}, line_color=YELLOW)"
                    )
                    lines.append(f"        self.play(Create(curve))")
                lines += [
                    f"        self.wait({dur:.2f})",
                    f"        self.play(FadeOut(ax{i}))",
                ]
        # geometric_step / highlight: best-effort fallback to title text
        else:
            lines += [
                f"        misc{i} = Text({_q(kind)}, font_size=24)",
                f"        self.play(FadeIn(misc{i}))",
                f"        self.wait({dur:.2f})",
                f"        self.play(FadeOut(misc{i}))",
            ]

    out_path.write_text("\n".join(lines))
    return out_path


def _find_manim_output(media_dir: Path, key: str) -> Path | None:
    for p in media_dir.rglob(f"manim_{key}.mp4"):
        return p
    return None


def _q(s: str) -> str:
    """Python-escape a string for safe inclusion as a literal."""
    return json.dumps(s)


def _key(scene: dict) -> str:
    blob = json.dumps({
        "title":  scene.get("title", ""),
        "n_beats": len(scene.get("beats") or []),
        "first":  (scene.get("beats") or [{}])[0],
    }, sort_keys=True)
    return hashlib.sha1(blob.encode()).hexdigest()[:16]
