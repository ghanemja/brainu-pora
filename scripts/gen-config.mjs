// Build-time config generator.
// Writes design/config.js from the BU_API_BASE env var so the deployed
// frontend points at the right backend without hardcoding it in the HTML.
//
// Netlify runs this via netlify.toml's build command. Locally it's a no-op
// unless you set BU_API_BASE.
//
//   BU_API_BASE=https://brain-university-api.onrender.com node scripts/gen-config.mjs

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "design", "config.js");

const base = (process.env.BU_API_BASE || "").trim();

const body = base
  ? `// Auto-generated by scripts/gen-config.mjs at deploy time.\n` +
    `window.BU_API_BASE = ${JSON.stringify(base)};\n`
  : `// Auto-generated by scripts/gen-config.mjs — no BU_API_BASE set,\n` +
    `// frontend will fall back to http://localhost:8080.\n`;

writeFileSync(out, body);
console.log(base
  ? `[gen-config] BU_API_BASE -> ${base}`
  : `[gen-config] BU_API_BASE unset; wrote local-dev fallback`);
